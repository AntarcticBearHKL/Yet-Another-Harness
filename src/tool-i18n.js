function toolDisplayName(name) {
  return String(name || '');
}

function toolDisplayDescription(name, fallback = '') {
  return (
    TOOL_I18N[String(name || '')]?.description ||
    String(fallback || '')
  );
}

function toolParamDescription(name, paramName) {
  const key = String(name || '');
  return (
    TOOL_I18N[key]?.params?.[paramName] ||
    PARAM_I18N[paramName] ||
    ''
  );
}

function toolTypeLabel(type) {
  return TYPE_I18N[String(type || '')] || String(type || '');
}

